#!/usr/bin/env python3
"""Regenerate context artifacts that must never drift from the manifest.

Outputs:
  docs/agentcity/state-of-build.md   feature status table and next milestone
  docs/repo-map.md                   shallow map of the working tree

Run after any status, path, command, or tool change:
  python scripts/generate-context.py
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs/PROJECT_MANIFEST.json"

STATE_OF_BUILD = ROOT / "docs/agentcity/state-of-build.md"
REPO_MAP = ROOT / "docs/repo-map.md"

STATUS_ORDER = {"implemented": 0, "partial": 1, "blocked": 2, "planned": 3}

MAP_PURPOSE = {
    "src/desktop": "Electron main, preload bridge, and React renderer",
    "src/backend": "FastAPI sidecar, mission engine, ADK agents, adapters",
    "src/skills": "Pinned local tool clones (gitignored; restored by script)",
    "docs": "Context pack, architecture, standards, runbooks",
    "scripts": "Bootstrap, doc validation, context generation",
    "docs/agentcity": "Product, security, reuse, tooling, and status records",
    "docs/architecture": "System design, diagrams, contracts, ER diagrams, ADRs",
    "docs/engineering": "Coding, testing, debugging, security, performance rules",
    "docs/runbooks": "Operational setup and recovery procedures",
    "docs/templates": "Reusable ADR, feature, incident, release, and handoff forms",
}

TOOL_PATHS = {
    "ADK Agent Builder": "src/skills/adk-agent-builder",
    "SkillBridge": "src/skills/skills-bridge",
}


def tool_commit(manifest: dict, name: str) -> str:
    for tool in manifest.get("tools", []):
        if tool.get("name") == name:
            return tool["commit"]
    raise SystemExit(f"Manifest is missing required tool '{name}'")


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def write_state_of_build(manifest: dict) -> None:
    features = sorted(
        manifest["features"],
        key=lambda item: (STATUS_ORDER.get(item["status"], 9), item["id"]),
    )
    counts: dict[str, int] = {}
    for feature in features:
        counts[feature["status"]] = counts.get(feature["status"], 0) + 1

    rows = []
    for feature in features:
        evidence = feature.get("evidence") or "—"
        notes = feature.get("notes") or ""
        rows.append(
            f"| `{feature['id']}` | {feature['name']} | **{feature['status']}** | {notes} | {evidence} |"
        )

    summary = " · ".join(f"{counts.get(key, 0)} {key}" for key in ("implemented", "partial", "blocked", "planned"))

    content = f"""---
title: State of Build
status: active
owner: integration
last_verified: {today()}
---

# State of Build

> Generated by `scripts/generate-context.py` from `docs/PROJECT_MANIFEST.json`.
> Do not edit by hand. Update the manifest and regenerate.

**Snapshot:** {today()} · **Milestone:** {manifest['project']['milestone']}
**Feature status:** {summary}

A runtime capability is never marked `implemented` without a test command, an
evidence file, and visible UI state. Foundation work (docs, tool pins) requires
the command and evidence but makes no UI claim. `mocked` and `blocked` are
recorded in the notes.

| ID | Capability | Status | Notes | Evidence |
|---|---|---|---|---|
{chr(10).join(rows)}

## Environment

| Item | Value |
|---|---|
| Platform | {manifest['environment']['platform']} |
| Python | {manifest['environment']['python']} |
| Node | {manifest['environment']['node']} |
| google-adk | {manifest['environment']['google_adk']} |
| MCP SDK | {manifest['environment']['mcp']} |
| RAM | {manifest['environment']['ram']} |
| Provider key | {"configured" if manifest['environment']['provider_configured'] else "not configured (Offline Mode)"} |

## Pinned tools

| Tool | Commit | License | State |
|---|---|---|---|
""" + "\n".join(
        f"| {tool['name']} | `{tool['commit']}` | {tool['license']} | {tool['state']} |"
        for tool in manifest["tools"]
    ) + f"""

## Next milestone

**{manifest['project']['next_milestone']['id']} — {manifest['project']['next_milestone']['name']}**

{manifest['project']['next_milestone']['summary']}

### Exit criteria

""" + "\n".join(f"- {item}" for item in manifest['project']['next_milestone']['exit_criteria']) + "\n"

    STATE_OF_BUILD.write_text(content, encoding="utf-8")


def walk_tree(base: Path, depth: int = 2) -> list[str]:
    lines: list[str] = []

    def visit(directory: Path, level: int) -> None:
        if level > depth:
            return
        entries = sorted(
            (
                entry
                for entry in directory.iterdir()
                if entry.name not in {".git", "node_modules", ".venv", "__pycache__", ".pytest_cache"}
                and not entry.name.startswith(".")
            ),
            key=lambda entry: (entry.is_file(), entry.name.lower()),
        )
        for entry in entries:
            rel = entry.relative_to(ROOT).as_posix()
            indent = "  " * (level - 1)
            if entry.is_dir():
                purpose = MAP_PURPOSE.get(rel, "")
                suffix = f" — {purpose}" if purpose else ""
                lines.append(f"{indent}- `{entry.name}/`{suffix}")
                visit(entry, level + 1)
            else:
                lines.append(f"{indent}- `{entry.name}`")

    visit(base, 1)
    return lines


def write_repo_map(manifest: dict) -> None:
    desktop = ROOT / "src/desktop"
    backend = ROOT / "src/backend"
    sections = []

    for label, path in (("Backend", backend), ("Desktop", desktop)):
        if path.exists():
            sections.append(f"### {label}\n\n" + "\n".join(walk_tree(path, 2)))
        else:
            sections.append(f"### {label}\n\n_Not created yet ({manifest['project']['milestone']})._")

    docs_tree = "\n".join(walk_tree(ROOT / "docs", 2))

    content = f"""---
title: Repository Map
status: active
owner: integration
last_verified: {today()}
---

# Repository Map

> Generated by `scripts/generate-context.py`. Regenerate after moving files.

## Top level

```text
AGENTS.md              Project constitution for humans and AI agents
README.md              Human setup and product overview
docs/                  Context pack, architecture, standards, runbooks
src/                   Application source and pinned tools
scripts/               Bootstrap and documentation tooling
```

## Application source

{chr(10).join(sections)}

## Documentation

{docs_tree}

## Tool clones

| Path | Tool | Pinned commit |
|---|---|---|
| `{TOOL_PATHS['ADK Agent Builder']}` | ADK Agent Builder | `{tool_commit(manifest, 'ADK Agent Builder')}` |
| `{TOOL_PATHS['SkillBridge']}` | SkillBridge | `{tool_commit(manifest, 'SkillBridge')}` |
"""

    REPO_MAP.write_text(content, encoding="utf-8")


def main() -> int:
    manifest = load_manifest()
    write_state_of_build(manifest)
    write_repo_map(manifest)
    print(f"Updated {STATE_OF_BUILD.relative_to(ROOT)} and {REPO_MAP.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
